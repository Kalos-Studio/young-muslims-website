import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "csv-parse/sync";
import { format } from "prettier";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = resolve(projectRoot, "data/neighbornets.csv");
const outputPath = resolve(
  projectRoot,
  "src/generated/brother-neighbornets.ts",
);
const requiredColumns = ["neighbor_net", "subregion", "latitude", "longitude"];

const source = readFileSync(inputPath, "utf8");
const header = parse(source, { to_line: 1 })[0];
const missingColumns = requiredColumns.filter(
  (column) => !header.includes(column),
);

if (missingColumns.length > 0) {
  throw new Error(
    `Missing required NeighborNet CSV columns: ${missingColumns.join(", ")}`,
  );
}

const rows = parse(source, {
  columns: true,
  skip_empty_lines: true,
  trim: true,
});
const ids = new Set();

const locations = rows.map((row, index) => {
  const rowNumber = index + 2;
  const name = requiredValue(row.neighbor_net, "neighbor_net", rowNumber);
  const region = requiredValue(row.subregion, "subregion", rowNumber);
  const latitude = coordinate(row.latitude, "latitude", rowNumber, -90, 90);
  const longitude = coordinate(
    row.longitude,
    "longitude",
    rowNumber,
    -180,
    180,
  );
  const id = `brothers-${slug(`${region}-${name}`)}`;

  if (ids.has(id)) {
    throw new Error(
      `Duplicate NeighborNet ID "${id}" generated from CSV row ${rowNumber}`,
    );
  }
  ids.add(id);

  return {
    id,
    name,
    branch: "brothers",
    status: "active",
    region,
    latitude,
    longitude,
  };
});

const generatedSource = `// Generated by scripts/generate-neighbornets.mjs. Do not edit directly.\nimport type { NeighborNetLocation } from "@/lib/neighbornets";\n\nexport const brotherLocations: NeighborNetLocation[] = ${JSON.stringify(locations, null, 2)};\n`;
const formattedSource = await format(generatedSource, { parser: "typescript" });

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, formattedSource);

console.log(`Generated ${locations.length} NeighborNet locations.`);

function requiredValue(value, column, row) {
  if (!value) {
    throw new Error(`Missing ${column} in NeighborNet CSV row ${row}`);
  }
  return value;
}

function coordinate(value, column, row, minimum, maximum) {
  const parsed = Number(value);
  if (!Number.isFinite(parsed) || parsed < minimum || parsed > maximum) {
    throw new Error(
      `Invalid ${column} "${value}" in NeighborNet CSV row ${row}`,
    );
  }
  return parsed;
}

function slug(value) {
  return value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}
